def build_question_message(
    question_data: dict,
    current_index: int,
    *,
    mode: str = "next",
    prev_question: dict | None = None,
    candidate_name: str | None = None,
    track_title: str | None = None,
    total: int = TOTAL_QUESTIONS,
) -> str:
    """
    Собирает реплику интервьюера с вопросом.

    mode:
      - "first"  — первый вопрос: приветствие ментора + вопрос;
      - "next"   — обычный переход к следующему вопросу;
      - "resume" — возврат после паузы (/continue, /start, после оплаты).
    """
    # Экранируем текст вопроса: в нём могут быть символы вроде "<" (например, "p99 < 50 мс"),
    # которые сломали бы HTML-разметку Telegram.
    question_text = html.escape(str(question_data.get("text", "")))
    number = current_index + 1
    footer = f"\n\n<i>Вопрос {number} из {total}</i>"

    if mode == "first":
        greeting = random.choice(_GREETINGS).format(
            name=_name_suffix(candidate_name),
            mentor=html.escape(MENTOR_NAME),
            track=html.escape(track_title or "выбранное направление"),
        )
        return f"{greeting}\n\n{question_text}{footer}"

    if mode == "resume":
        return f"{random.choice(_RESUME)}\n\n{question_text}{footer}"

    # mode == "next"
    category = str(question_data.get("category", "")).lower()
    prev_category = str((prev_question or {}).get("category", "")).lower()
    topic_changed = bool(prev_question) and category != prev_category

    if number == total:
        lead_in = random.choice(_LAST)
    elif topic_changed and "техническ" in category:
        lead_in = random.choice(_TO_TECHNICAL)
    elif topic_changed and "поведенческ" in category:
        lead_in = random.choice(_TO_BEHAVIORAL)
    elif random.random() < 0.3:
        # Иногда живой интервьюер просто задаёт следующий вопрос без всяких связок.
        lead_in = ""
    else:
        lead_in = random.choice(_NEXT)

    if lead_in:
        return f"{lead_in}\n\n{question_text}{footer}"
    return f"{question_text}{footer}"


def format_question_card(question_data: dict, current_index: int) -> str:
    """Старое имя функции — оставлено для обратной совместимости, теперь подаёт вопрос «по-человечески»."""
    return build_question_message(question_data, current_index, mode="next")


