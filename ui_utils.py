def generate_progress_bar(current: int, total: int = TOTAL_QUESTIONS) -> str:
    """Моноширинный прогресс-бар из 10 сегментов (оставлен для обратной совместимости)."""
    total = max(1, total)
    current = min(total, max(0, current))

    filled_blocks = math.floor((current / total) * 10)
    empty_blocks = 10 - filled_blocks
    percent = int((current / total) * 100)

    bar = "■" * filled_blocks + "□" * empty_blocks
    return f"<code>Прогресс: [{bar}] {percent}% • Вопрос {current}/{total}</code>"


def first_name(full_name: str | None) -> str | None:
    """Достаёт имя из Telegram full_name. Если там ник без букв или пусто — вернёт None."""
    if not full_name or not full_name.strip():
        return None
    candidate = full_name.strip().split()[0]
    if not any(ch.isalpha() for ch in candidate) or len(candidate) > 20:
        return None
    return html.escape(candidate)


def typing_delay_for(text: str) -> float:
    """Сколько секунд «печатать» перед отправкой сообщения — как будто человек набирает текст."""
    return min(3.0, 0.8 + len(text) / 200)


def _name_suffix(name: str | None) -> str:
    return f", {name}" if name else ""


