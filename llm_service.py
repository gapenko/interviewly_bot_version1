async def generate_final_report(qa_pairs: list[dict], track_title: str) -> str:
    """Формирует итоговое заключение интервьюера по Hard & Soft Skills."""
    transcript_lines = [f"Направление: {track_title}", f"Всего вопросов в собеседовании: {len(qa_pairs)}"]
    for i, pair in enumerate(qa_pairs, start=1):
        score = pair.get("score")
        score_note = f" (оценка по ходу собеседования: {score}/10)" if score else ""
        transcript_lines.append(f"{i}. Вопрос: {pair['question']}\n   Ответ{score_note}: {pair['answer']}")
    transcript = "\n\n".join(transcript_lines)

    try:
        response = await client.messages.create(
            model=LLM_MODEL,
            max_tokens=1500,
            system=FINAL_REPORT_SYSTEM_PROMPT.format(track=track_title),
            messages=[{"role": "user", "content": transcript}],
        )
        return _extract_text(response)
    except Exception as e:
        logger.exception("Ошибка при формировании отчета: %s", e)
        return (
            "Сформировать итоговый разбор сейчас не удалось из-за высокой нагрузки на сервис. "
            "Пожалуйста, отправьте команду /continue немного позже — разбор будет подготовлен повторно."
        )


